# Ключевая ставка Банка России — по словосочетанию, а не по слову «ставка»: «ставка НДС», «ставки аренды»,
# «ставка купона», «ставка на качество» и ставка ФРС — не она.
KEY_RATE = re.compile(r"ключев\w* ставк|денежно-кредитн|\bдкп\b")
# «ключев» — только вплотную к «ставке» (KEY_RATE): «ключевым фактором… ставка на качество» — не она
RATE_CONTEXT = re.compile(r"\bцб\b|банк\w* росси|регулятор|центробанк|\bдкп\b|денежно-кредит")
# слово рядом со «ставкой» говорит, что это ставка налога, сбора, аренды, купона или ипотеки
NOT_KEY_RATE = re.compile(r"ндс|налог|пошлин|утильсбор|акциз|аренд|купон|ипотек")
# чужой центральный банк; «ЦБ» без страны в русской новости — Банк России
FOREIGN_CB = re.compile(
    r"\bфрс\b|\bецб\b|федеральн\w* резерв|\bfed\b|\becb\b|народн\w* банк\w* кита|"
    r"банк\w* (?:англии|японии|китая|кореи|канады|турции|казахстана|индии)|"
    r"(?:\bцб|центробанк\w*|центральн\w* банк\w*) (?:турци|кита|кнр|инди|казахстан|узбекистан|беларус|белорус|армени|"
    r"бразили|япони|англи|сша|европ|ес\b)")
RUS_CB = re.compile(r"банк\w* росси|\bцб (?:рф|россии)\b|российск\w* (?:регулятор|центробанк|цб)")
SENTENCE_END = re.compile(r"(?<=[.!?…])\s+|\n+")


def key_rate_in(t: str) -> bool:
    """Есть ли в тексте (нижний регистр) ключевая ставка Банка России. Предложение засчитывается, если в нём
    «ключевая ставка», ДКП или «денежно-кредитная политика» — либо «ставка», рядом с которой нет налога,
    сбора, аренды, купона и ипотеки, а в том же предложении назван ЦБ или регулятор. Предложение о чужом
    центральном банке (ФРС, ЕЦБ, «ЦБ Турции») без Банка России не засчитывается."""
    for s in SENTENCE_END.split(t):
        if FOREIGN_CB.search(s) and not RUS_CB.search(s):
            continue
        if KEY_RATE.search(s):
            return True
        if not RATE_CONTEXT.search(s):
            continue
        for m in re.finditer(r"(?:(\S+) )?ставк\w*((?: \S+){0,3})", s):
            if not NOT_KEY_RATE.search((m.group(1) or "") + m.group(2)):
                return True
    return False


