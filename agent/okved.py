# Словосочетания, где слово отрасли или темы стоит в другом смысле: «розничные инвесторы» — не ритейл,
# «импортозамещение» — не курс, «Автомобилист» — хоккейный клуб, «бумажная нефть» — фьючерсы,
# «запас золота», «золотовалютные резервы» и «цифровое золото» — резервы ЦБ и финансовый продукт, не металлы.
# Вырезаются перед поиском основ.
NOISE = re.compile(r"розничн\w* (?:инвестор|клиент|вкладчик|кредитован|бизнес\w* банк)\w*|импортозамещ\w*|автомобилист\w*|"
                   r"бумажн\w* (?:нефт|рын|золот)\w*|запас\w* золот\w*|золотовалютн\w*|цифров\w* золот\w*")
# Стоп-список: слова, которые начинаются с основы отрасли, но не про неё — «оптоволокно» (не опт),
# «складывается», «складной» (не склад), фамилии «Руденко», «Сахаров».
STOPLIST = re.compile(r"(?<![а-яa-z0-9])(?:оптоволок|складыва|складн|складчин|руденко|сахаров)[а-яa-z0-9-]*")


def _norm(text: str) -> str:
    t = re.sub(r"\s+", " ", text.lower().replace("ё", "е"))
    return " " + STOPLIST.sub(" ", NOISE.sub(" ", t)) + " "


def _has(t: str, stem) -> bool:
    """Основа должна стоять в начале слова: «сталь» не должна находиться в «остальных»."""
    return _count(t, stem) > 0


@lru_cache(maxsize=1024)
def _stem_rx(stem: str) -> re.Pattern:
    # пробел в конце основы («меди », «стали ») значит «слово целиком»: иначе «меди» находится в «медиа»
    end = r"(?![а-яa-z0-9])" if stem.endswith(" ") else ""
    return re.compile(r"(?<![а-яa-z0-9])" + re.escape(stem.strip()) + end)


def _count(t: str, stem) -> int:
    """Сколько раз основа (строка или регулярное выражение из SECTOR_STEMS) встречается в начале слова."""
    return len((stem if isinstance(stem, re.Pattern) else _stem_rx(stem)).findall(t))


def sectors_in(text: str) -> list[str]:
    t = _norm(text)
    return sorted(code for code, stems in SECTOR_STEMS.items() if any(_has(t, s) for s in stems))


@lru_cache(maxsize=4096)
def passing_sectors(title: str, text: str) -> frozenset[str]:
    """Отрасли, упомянутые вскользь: их слова нет в заголовке, а в начале текста (первые 600 знаков, как
    при разметке события) оно встречается один раз. «Маск ограничил доступ к Starshield… из-за ударов по НПЗ»
    — новость не про нефтепереработку, хотя «НПЗ» в ней есть. Заголовок, повторённый в начале текста
    (посты Telegram), не считается."""
    title, text = title.strip(), text.strip()
    body = text[len(title):] if title and text.startswith(title) else text
    head, t = _norm(title), _norm(body[:600])
    out = set()
    for code, stems in SECTOR_STEMS.items():
        if any(_has(head, s) for s in stems):
            continue
        if sum(_count(t, s) for s in stems) == 1:
            out.add(code)
    return frozenset(out)


def topics_in(text: str, title: str | None = None) -> list[str]:
    """Темы новости. Если передан заголовок, тема засчитывается, когда её слово есть в заголовке
    или в тексте встречаются хотя бы две разные основы темы: одно случайное слово в длинном
    посте («…остался должен…») тему не делает."""
    t = _norm(text)
    head = _norm(title) if title is not None else None
    found = []
    for topic, stems in TOPIC_STEMS.items():
        if topic in TOPIC_TEST:  # тема определяется словосочетанием, а не отдельными словами
            if TOPIC_TEST[topic](t if head is None else head + ".\n" + t):
                found.append(topic)
            continue
        hits = {s for s in stems if _has(t, s)}
        if head is None and hits or head is not None and (any(_has(head, s) for s in stems) or len(hits) >= 2):
            found.append(topic)
    if sectors_in(text if head is None else (title or "") + " " + text[:600]):
        found.append("отрасль")
    return found
