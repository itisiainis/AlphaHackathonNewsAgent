def country_name(c: str) -> str:
    """«КИТАЙ» → «Китай», аббревиатуры («ОАЭ», «США») не трогаем."""
    return c.capitalize() if c.isupper() and len(c) > 3 else c


def short_name(okved2: str | None) -> str:
    return SHORT_NAMES.get((okved2 or "")[:2], "Прочее")


def label(okved2: str) -> str:
    """«Оптовая торговля (46)» — подпись для данных и трассы, где код нужен для сверки."""
